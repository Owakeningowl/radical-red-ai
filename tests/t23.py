from lab import *
L = Lab(); b = L.b
SN = 143
FW = dict(moves=['Tackle', 'Pound', 'Scratch', 'Slash'], atk=30, spa=30, hp=300, maxhp=300, spe=50)
ATK = ['Flamethrower', 'Psychic', 'Ice Beam', 'Tackle']
AIW = dict(moves=ATK, hp=200, maxhp=300, atk=60, spa=60, spe=100)
glass = dict(species=SN, moves=['Tackle', 'Pound', 'Scratch', 'Slash'], dfn=5, spd=5, spe=20, hp=30, atk=30, spa=30)
sweep = dict(species=SN, moves=['Earthquake', 'Pound', 'Scratch', 'Slash'], dfn=300, spd=300, spe=300, hp=300, atk=900, spa=30)
def R(t, ai, foe, n=40):
    r = L.rate(ai, foe, n)
    s = sum(v for k, v in r.items() if k != 'stay')
    print(f'{t}: {s}/{n} = {100*s//n}%'); sys.stdout.flush()
FB = dict(FW, atk=900)
L.bench(sweep, glass); R('foe KOs, AI slower, bench fast KO', dict(AIW, spe=30), FB)
L.bench(sweep, glass); R('foe KOs, AI faster, bench fast KO', AIW, FB)
L.bench(sweep, glass); R('harmless foe, AI cannot KO, bench fast KO', AIW, FW)
L.bench(sweep, glass); R('harmless foe, AI can 2HKO, bench fast KO', dict(AIW, spa=300), FW)
L.bench(sweep, glass); R('harmless foe, AI can KO, bench fast KO', dict(AIW, spa=900), FW)
FM = dict(FW, spa=30, atk=250)
L.bench(sweep, glass); R('foe 3HKOs, AI cannot KO, bench fast KO', AIW, FM)
wall = dict(species=SN, moves=['Tackle', 'Pound', 'Scratch', 'Slash'], dfn=900, spd=900, spe=20, hp=300, atk=30, spa=30)
L.bench(wall, glass); R('foe 3HKOs, AI cannot 2HKO, bench wall', AIW, FM, 80)
L.bench(wall, glass); R('foe 3HKOs, AI can 2HKO, bench wall', dict(AIW, spa=300), FM, 80)
L.bench(wall, glass); R('foe does under 1/3, AI cannot 2HKO, bench wall', dict(AIW, hp=300), FM)
jolt = dict(species=135, moves=['Tackle', 'Pound', 'Scratch', 'Slash'], dfn=200, spd=200, spe=100, hp=300, atk=30, spa=30)
FE = dict(FW, moves=['Thunderbolt', 'Growl', 'Leer', 'Tail Whip'], spa=40)
L.bench(jolt, glass); R('absorb: weak Thunderbolt, foe stall style', AIW, FE)
FE2 = dict(FW, moves=['Thunderbolt', 'Pound', 'Scratch', 'Tackle'], spa=40)
L.bench(jolt, glass); R('absorb: weak Thunderbolt, foe attacker', AIW, FE2)
FE3 = dict(FW, moves=['Thunderbolt', 'Pound', 'Scratch', 'Tackle'], spa=300, atk=5)
L.bench(jolt, glass); R('absorb: strong Thunderbolt, foe attacker', dict(AIW,hp=300), FE3)
L.bench(jolt, glass); R('absorb: strong T-bolt, AI can KO foe', dict(AIW,hp=300,spa=900), FE3)
FE4 = dict(FW, moves=['Tackle', 'Pound', 'Scratch', 'Thunderbolt'], spa=40, atk=200)
L.bench(jolt, glass); R('absorb: T-bolt not predicted', dict(AIW,hp=300), FE4)
L.quit()
