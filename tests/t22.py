def S(t, probe, ai={}, foe={}, base=AT, n=3):
    a = dict(moves=base + [probe], hp=200, maxhp=300, spe=100); a.update(ai)
    f = dict(FW); f.update(foe)
    r = L.run(a, f, n)
    v = sorted(set(x[len(base)] for x in r))
    print(f'{t}: {probe} {"/".join(map(str,v))} (style {L.style()}, switched {L.switched}/{L.total})'); sys.stdout.flush()
